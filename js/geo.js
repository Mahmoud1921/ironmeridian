// Miller cylindrical projection into "world units" (roughly degrees).
GEO.project = function (lon, lat) {
  const phi = lat * Math.PI / 180;
  const y = 1.25 * Math.log(Math.tan(Math.PI / 4 + 0.4 * phi)) * 180 / Math.PI;
  return [lon, -y];
};
GEO.unproject = function (x, y) {
  const my = -y * Math.PI / 180;
  const phi = (Math.atan(Math.exp(my / 1.25)) - Math.PI / 4) / 0.4;
  return [x, phi * 180 / Math.PI];
};
GEO.haversineKm = function (lon1, lat1, lon2, lat2) {
  const R = 6371, r = Math.PI / 180;
  const dLat = (lat2 - lat1) * r, dLon = (lon2 - lon1) * r;
  const a = Math.sin(dLat / 2) ** 2 + Math.cos(lat1 * r) * Math.cos(lat2 * r) * Math.sin(dLon / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(a));
};
